#!/usr/bin/env python3
"""
Convert the notebook's exported test vectors into a C header for the RISC-V firmware.

Usage (from the fw folder):
    python make_test_vectors.py <export_dir>/test_vectors [count]

    count = how many beats to include (default 2). Half are taken from the N beats and
            half from the ABN beats. Simulation takes several minutes per beat, so keep it
            small in ModelSim. Use 32 (all) on the board.

Output: test_vectors.h with
    TV_N                    number of test beats
    TV_WIN[TV_N*128]        raw ADC window (int16)
    TV_RR[TV_N*4]           integer RR features (int32)
    TV_LOGITS[TV_N*NCLS]    expected logits from the Python integer model (int32)
    TV_PRED[TV_N]           expected class
    TV_LABEL[TV_N]          true label (from the MIT-BIH annotation)
"""
import os
import sys

WIN, NRR = 128, 4


def read_hex(path, bits):
    vals = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            v = int(line, 16)
            if v >= 1 << (bits - 1):        # two's complement -> signed
                v -= 1 << bits
            vals.append(v)
    return vals


def main():
    tv_dir = sys.argv[1] if len(sys.argv) > 1 else "test_vectors"
    count = int(sys.argv[2]) if len(sys.argv) > 2 else 2

    win = read_hex(os.path.join(tv_dir, "window.hex"), 16)
    rr = read_hex(os.path.join(tv_dir, "rr.hex"), 32)
    logits = read_hex(os.path.join(tv_dir, "logits.hex"), 16)
    pred = read_hex(os.path.join(tv_dir, "pred.hex"), 8)
    label = read_hex(os.path.join(tv_dir, "label.hex"), 8)

    n_all = len(pred)
    ncls = len(logits) // n_all
    assert len(win) == n_all * WIN and len(rr) == n_all * NRR, "inconsistent test-vector files"

    # pick half N (label 0) and half ABN (label 1), in file order
    idx_n = [i for i in range(n_all) if label[i] == 0]
    idx_a = [i for i in range(n_all) if label[i] != 0]
    count = max(1, min(count, n_all))
    k_a = min(len(idx_a), count // 2)
    k_n = min(len(idx_n), count - k_a)
    sel = sorted(idx_n[:k_n] + idx_a[:k_a])

    def arr(ctype, name, values, per_line=16):
        lines = []
        for i in range(0, len(values), per_line):
            lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]))
        return f"static const {ctype} {name}[{len(values)}] = {{\n" + ",\n".join(lines) + "\n};\n"

    with open("test_vectors.h", "w") as f:
        f.write("// Auto-generated by make_test_vectors.py from the notebook export - do not edit\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define TV_N {len(sel)}\n")
        f.write(f"#define TV_NCLS {ncls}\n")
        f.write(f"// original vector indices: {sel}\n\n")
        f.write(arr("int16_t", "TV_WIN", [win[i * WIN + j] for i in sel for j in range(WIN)]))
        f.write(arr("int32_t", "TV_RR", [rr[i * NRR + j] for i in sel for j in range(NRR)]))
        f.write(arr("int32_t", "TV_LOGITS", [logits[i * ncls + j] for i in sel for j in range(ncls)]))
        f.write(arr("uint8_t", "TV_PRED", [pred[i] for i in sel]))
        f.write(arr("uint8_t", "TV_LABEL", [label[i] for i in sel]))

    print(f"test_vectors.h written: {len(sel)} beats (N: {k_n}, ABN: {k_a}), indices {sel}")


if __name__ == "__main__":
    main()
